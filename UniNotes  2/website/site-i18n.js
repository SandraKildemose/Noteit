const siteLangs = [
  { code: 'da', label: 'DA' },
  { code: 'en', label: 'EN' },
  { code: 'sv', label: 'SV' },
  { code: 'no', label: 'NO' },
  { code: 'de', label: 'DE' },
  { code: 'fr', label: 'FR' },
  { code: 'es', label: 'ES' },
];

function siteLang() {
  const saved = localStorage.getItem('noteit-site-lang');
  if (saved && siteI18n[saved]) return saved;
  const nav = (navigator.language || 'da').slice(0, 2);
  if (siteI18n[nav]) return nav;
  return 'da';
}

function t(key) {
  const lang = siteLang();
  return siteI18n[lang]?.[key] ?? siteI18n.da[key] ?? key;
}

function applySiteLang(lang) {
  if (!siteI18n[lang]) return;
  localStorage.setItem('noteit-site-lang', lang);
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (key) el.textContent = t(key);
  });
  document.title = t('title');
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.content = t('meta');
  const sel = document.getElementById('siteLang');
  if (sel) sel.value = lang;
}

document.addEventListener('DOMContentLoaded', () => {
  const sel = document.getElementById('siteLang');
  if (sel) {
    sel.innerHTML = siteLangs.map(l => `<option value="${l.code}">${l.label}</option>`).join('');
    sel.value = siteLang();
    sel.addEventListener('change', () => applySiteLang(sel.value));
  }
  applySiteLang(siteLang());
});
